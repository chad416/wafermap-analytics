"""Generate the report artefacts the README quotes, from the metric JSON files and models.

* ``reports/metrics/summary.md``   - model comparison + per-class table (pasted into README)
* ``reports/metrics/latency.json`` - single-wafer and batch inference latency per model
* ``reports/figures/per_class_f1.png`` - per-class test F1, baseline vs CNN
* ``reports/figures/class_examples.png`` - one random training-split example per class

Nothing here touches the test split except reading the stored test metrics.
"""

from __future__ import annotations

import json
import logging
import platform
import time
from pathlib import Path
from typing import Any

import numpy as np

from wafermap import wafer
from wafermap.constants import CLASSES
from wafermap.features.build import load_labelled
from wafermap.ml.predict import ModelRegistry

log = logging.getLogger(__name__)


def _load(reports_dir: Path, name: str) -> dict[str, Any]:
    return dict(json.loads((reports_dir / "metrics" / f"{name}.json").read_text()))


def latency(model_dir: Path, processed_dir: Path, n: int = 500, seed: int = 0) -> dict[str, Any]:
    """Median / p95 latency for one wafer per call, and throughput for a batch of ``n``.

    Uses validation-split maps (any real maps would do; no labels are used).
    """
    data = load_labelled(processed_dir)
    rng = np.random.default_rng(seed)
    idx = rng.choice(np.flatnonzero(data["split"] == "val"), size=n, replace=False)
    maps = [wafer.decode(data["map_zlib"][i], data["rows"][i], data["cols"][i]) for i in idx]
    reg = ModelRegistry(model_dir)
    out: dict[str, Any] = {"cpu": platform.processor() or platform.machine(), "n": n}
    for name in reg.names():
        clf = reg.get(name)
        clf.predict_proba(maps[:5])  # warm-up (session creation, lazy imports)
        single = []
        for m in maps[:200]:
            t0 = time.perf_counter()
            clf.predict_proba([m])
            single.append((time.perf_counter() - t0) * 1000)
        t0 = time.perf_counter()
        clf.predict_proba(maps)
        batch_s = time.perf_counter() - t0
        out[name] = {
            "single_ms_median": round(float(np.median(single)), 2),
            "single_ms_p95": round(float(np.percentile(single, 95)), 2),
            "batch_wafers_per_s": round(n / batch_s, 1),
        }
    return out


def per_class_table(base: dict[str, Any], cnn: dict[str, Any]) -> str:
    lines = [
        "| Class | Test support | Baseline P / R / F1 | CNN P / R / F1 |",
        "|---|---:|---|---|",
    ]
    for c in CLASSES:
        b, n = base["test"]["per_class"][c], cnn["test"]["per_class"][c]
        lines.append(
            f"| {c} | {b['support']:,} | {b['precision']:.3f} / {b['recall']:.3f} / "
            f"**{b['f1']:.3f}** | {n['precision']:.3f} / {n['recall']:.3f} / **{n['f1']:.3f}** |"
        )
    return "\n".join(lines)


def summary_markdown(base: dict[str, Any], cnn: dict[str, Any], lat: dict[str, Any]) -> str:
    def row(name: str, r: dict[str, Any]) -> str:
        t, v = r["test"], r["val"]
        lo, hi = t["macro_f1_ci95_lot_bootstrap"]
        lt = lat.get(name, {})
        return (
            f"| {name} | {v['macro_f1']:.3f} | **{t['macro_f1']:.3f}** [{lo:.3f}, {hi:.3f}] | "
            f"{t['macro_f1_defect_classes']:.3f} | {t['balanced_accuracy']:.3f} | "
            f"{t['accuracy']:.3f} | {lt.get('single_ms_median', float('nan')):.1f} ms | "
            f"{lt.get('batch_wafers_per_s', float('nan')):,.0f} |"
        )

    head = (
        "| Model | Val macro-F1 | Test macro-F1 [95 % lot-bootstrap CI] | Test macro-F1 "
        "(8 defect classes) | Test balanced acc. | Test accuracy | Latency, 1 wafer (median) "
        "| Batch throughput (wafers/s) |\n|---|---:|---:|---:|---:|---:|---:|---:|"
    )
    return "\n".join(
        [
            "<!-- generated by `wafermap report` - do not edit by hand -->",
            "",
            head,
            row("baseline", base),
            row("cnn", cnn),
            "",
            f"Test split: {base['test']['n']:,} wafers from held-out lots. "
            f"Latency measured on `{lat['cpu']}`, single process, CPU only.",
            "",
            per_class_table(base, cnn),
            "",
        ]
    )


def plot_per_class(base: dict[str, Any], cnn: dict[str, Any], path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    x = np.arange(len(CLASSES))
    fig, ax = plt.subplots(figsize=(9, 3.8), dpi=150)
    for off, (label, r, color) in zip(
        (-0.2, 0.2), (("LightGBM baseline", base, "#9ca3af"), ("CNN", cnn, "#2563eb")), strict=True
    ):
        vals = [r["test"]["per_class"][c]["f1"] for c in CLASSES]
        ax.bar(
            x + off, vals, 0.4, label=f"{label} (macro {r['test']['macro_f1']:.3f})", color=color
        )
    ax.set_xticks(x, CLASSES, rotation=30, ha="right")
    ax.set_ylim(0.5, 1.0)
    ax.set_ylabel("test F1")
    ax.set_title("Per-class F1 on the held-out test lots", fontsize=10)
    ax.legend(frameon=False, loc="lower left")
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(axis="y", color="#e5e7eb")
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def plot_examples(processed_dir: Path, path: Path, seed: int = 3) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import ListedColormap

    data = load_labelled(processed_dir)
    rng = np.random.default_rng(seed)
    cmap = ListedColormap(["#ffffff", "#c9d4e2", "#d1343b"])
    fig, axes = plt.subplots(1, len(CLASSES), figsize=(14, 2.0), dpi=150)
    for k, (ax, c) in enumerate(zip(axes, CLASSES, strict=True)):
        pool = np.flatnonzero((data["y"] == k) & (data["split"] == "train"))
        i = int(rng.choice(pool))
        m = wafer.decode(data["map_zlib"][i], data["rows"][i], data["cols"][i])
        ax.imshow(m, cmap=cmap, vmin=0, vmax=2, interpolation="nearest")
        ax.set_title(c, fontsize=9)
        ax.axis("off")
    fig.suptitle(
        "WM-811K failure-pattern classes (one training-split example each; red = failing die)",
        fontsize=9,
        y=0.02,
        va="bottom",
    )
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.savefig(path)
    plt.close(fig)


def build_report(processed_dir: Path, model_dir: Path, reports_dir: Path) -> None:
    base, cnn = _load(reports_dir, "baseline"), _load(reports_dir, "cnn")
    lat = latency(model_dir, processed_dir)
    (reports_dir / "metrics" / "latency.json").write_text(
        json.dumps(lat, indent=2) + "\n", newline="\n"
    )
    (reports_dir / "metrics" / "summary.md").write_text(
        summary_markdown(base, cnn, lat), newline="\n"
    )
    figs = reports_dir / "figures"
    plot_per_class(base, cnn, figs / "per_class_f1.png")
    plot_examples(processed_dir, figs / "class_examples.png")
    log.info("report written to %s", reports_dir)
